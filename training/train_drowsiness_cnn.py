"""
train_drowsiness_cnn.py  (fixed version)
Trains a small CNN to classify an eye image as OPEN or CLOSED.

Data folder (real images only - nothing is generated by this script):
    dataset/eye_dataset/closed/*.png|jpg
    dataset/eye_dataset/open/*.png|jpg

What this script does
  1. Splits images into TRAIN 70% / VALIDATION 15% / TEST 15%.
     - If file names look like MRL (s0001_...), the split is by PERSON so the
       same person never appears in two sets (otherwise accuracy is inflated).
  2. Trains with augmentation on train only; validation/test use no augmentation.
  3. Keeps the epoch with the best validation accuracy.
  4. Evaluates ONCE on the untouched test set.
  5. Saves: models/eye_cnn.pth, reports/eye_cnn_history.png,
            reports/eye_cnn_confusion_matrix.png, reports/eye_cnn_metrics.json

Run from project root:   python training/train_drowsiness_cnn.py
"""
import os, re, sys, json, random
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import torch, torch.nn as nn, torch.optim as optim
from torch.utils.data import DataLoader, Subset
from torchvision import datasets, transforms
from sklearn.model_selection import GroupShuffleSplit, train_test_split
from sklearn.metrics import classification_report, confusion_matrix

CFG = dict(data_dir="dataset/eye_dataset", model_out="models/eye_cnn.pth",
           img_size=24, batch_size=64, epochs=25, lr=1e-3, seed=42,
           device="cuda" if torch.cuda.is_available() else "cpu")

random.seed(CFG["seed"]); np.random.seed(CFG["seed"]); torch.manual_seed(CFG["seed"])
os.makedirs("models", exist_ok=True); os.makedirs("reports", exist_ok=True)

S = CFG["img_size"]
train_tf = transforms.Compose([transforms.Grayscale(1), transforms.Resize((S, S)),
    transforms.RandomRotation(10), transforms.ColorJitter(0.3, 0.3),
    transforms.ToTensor(), transforms.Normalize([0.5], [0.5])])
eval_tf = transforms.Compose([transforms.Grayscale(1), transforms.Resize((S, S)),
    transforms.ToTensor(), transforms.Normalize([0.5], [0.5])])


class EyeCNN(nn.Module):
    def __init__(self):
        super().__init__()
        self.features = nn.Sequential(
            nn.Conv2d(1, 32, 3, padding=1), nn.BatchNorm2d(32), nn.ReLU(), nn.MaxPool2d(2),
            nn.Conv2d(32, 64, 3, padding=1), nn.BatchNorm2d(64), nn.ReLU(), nn.MaxPool2d(2),
            nn.Conv2d(64, 128, 3, padding=1), nn.BatchNorm2d(128), nn.ReLU(),
            nn.AdaptiveAvgPool2d((3, 3)))
        self.classifier = nn.Sequential(nn.Dropout(0.5), nn.Linear(128 * 9, 128), nn.ReLU(),
                                        nn.Dropout(0.3), nn.Linear(128, 2))

    def forward(self, x):
        return self.classifier(self.features(x).flatten(1))


def make_splits(ds):
    n = len(ds); idx = np.arange(n); labels = np.array(ds.targets)
    names = [os.path.basename(p) for p, _ in ds.samples]
    groups = np.array([re.match(r"(s\d+)", f).group(1) if re.match(r"(s\d+)", f) else f for f in names])
    if len(set(groups)) >= 10 and len(set(groups)) < n:        # MRL-style: split by person
        print(f"[INFO] Splitting by person ({len(set(groups))} subjects).")
        g1 = GroupShuffleSplit(1, test_size=0.30, random_state=CFG["seed"])
        tr, rest = next(g1.split(idx, labels, groups))
        g2 = GroupShuffleSplit(1, test_size=0.50, random_state=CFG["seed"])
        va_i, te_i = next(g2.split(rest, labels[rest], groups[rest]))
        return tr, rest[va_i], rest[te_i]
    print("[INFO] No subject IDs in file names -> stratified random split "
          "(accuracy may be slightly optimistic; say so in your report).")
    tr, rest = train_test_split(idx, test_size=0.30, stratify=labels, random_state=CFG["seed"])
    va, te = train_test_split(rest, test_size=0.50, stratify=labels[rest], random_state=CFG["seed"])
    return tr, va, te


def run_epoch(model, loader, criterion, optimizer=None):
    train = optimizer is not None
    model.train(train)
    loss_sum, correct, n = 0.0, 0, 0
    with torch.set_grad_enabled(train):
        for x, y in loader:
            x, y = x.to(CFG["device"]), y.to(CFG["device"])
            out = model(x); loss = criterion(out, y)
            if train:
                optimizer.zero_grad(); loss.backward(); optimizer.step()
            loss_sum += loss.item() * len(x); correct += (out.argmax(1) == y).sum().item(); n += len(x)
    return loss_sum / n, 100.0 * correct / n


def main():
    if not os.path.isdir(CFG["data_dir"]):
        sys.exit(f"[ERROR] '{CFG['data_dir']}' not found. Download a real eye dataset first "
                 f"(open/ and closed/ sub-folders). Nothing was trained.")
    base = datasets.ImageFolder(CFG["data_dir"])
    if len(base.classes) != 2 or len(base) < 200:
        sys.exit(f"[ERROR] Need exactly 2 class folders and >=200 images. Found {base.classes}, {len(base)} images.")
    print(f"[INFO] Device={CFG['device']}  classes={base.classes}  images={len(base)}")

    tr, va, te = make_splits(base)
    print(f"[INFO] train={len(tr)} val={len(va)} test={len(te)}")
    ds_train = datasets.ImageFolder(CFG["data_dir"], transform=train_tf)   # separate objects =
    ds_eval = datasets.ImageFolder(CFG["data_dir"], transform=eval_tf)     # augmentation only on train
    dl = lambda ds, ids, sh: DataLoader(Subset(ds, ids), CFG["batch_size"], shuffle=sh, num_workers=0)
    train_l, val_l, test_l = dl(ds_train, tr, True), dl(ds_eval, va, False), dl(ds_eval, te, False)

    model = EyeCNN().to(CFG["device"]); crit = nn.CrossEntropyLoss()
    opt = optim.Adam(model.parameters(), lr=CFG["lr"])
    sched = optim.lr_scheduler.CosineAnnealingLR(opt, CFG["epochs"])
    hist = {k: [] for k in ("train_loss", "val_loss", "train_acc", "val_acc")}
    best = -1.0
    for ep in range(1, CFG["epochs"] + 1):
        tl, ta = run_epoch(model, train_l, crit, opt); vl, vacc = run_epoch(model, val_l, crit)
        sched.step()
        for k, v in zip(hist, (tl, vl, ta, vacc)): hist[k].append(v)
        print(f"Epoch {ep:2d}/{CFG['epochs']}  train_loss={tl:.4f} train_acc={ta:.2f}%  val_loss={vl:.4f} val_acc={vacc:.2f}%")
        if vacc > best:
            best = vacc
            torch.save({"state_dict": model.state_dict(), "classes": base.classes,
                        "img_size": S}, CFG["model_out"])
            print(f"   saved best model (val_acc={best:.2f}%)")

    # history plot
    fig, (a, b) = plt.subplots(1, 2, figsize=(11, 4))
    a.plot(hist["train_loss"], label="train"); a.plot(hist["val_loss"], label="validation"); a.set_title("Loss"); a.legend()
    b.plot(hist["train_acc"], label="train"); b.plot(hist["val_acc"], label="validation"); b.set_title("Accuracy (%)"); b.legend()
    for ax in (a, b): ax.set_xlabel("Epoch")
    plt.tight_layout(); plt.savefig("reports/eye_cnn_history.png", dpi=120); plt.close()

    # final test on unseen data, using the BEST saved weights
    model.load_state_dict(torch.load(CFG["model_out"], map_location=CFG["device"])["state_dict"])
    model.eval(); yt, yp = [], []
    with torch.no_grad():
        for x, y in test_l:
            yp += model(x.to(CFG["device"])).argmax(1).cpu().tolist(); yt += y.tolist()
    rep = classification_report(yt, yp, target_names=base.classes, output_dict=True)
    print("\n=== TEST SET RESULTS (data never used for training or model selection) ===")
    print(classification_report(yt, yp, target_names=base.classes))
    cm = confusion_matrix(yt, yp)
    plt.figure(figsize=(4.5, 4)); plt.imshow(cm, cmap="Blues")
    for (i, j), v in np.ndenumerate(cm): plt.text(j, i, v, ha="center", va="center")
    plt.xticks([0, 1], base.classes); plt.yticks([0, 1], base.classes)
    plt.xlabel("Predicted"); plt.ylabel("Actual"); plt.title("Eye CNN - test set")
    plt.tight_layout(); plt.savefig("reports/eye_cnn_confusion_matrix.png", dpi=120); plt.close()
    json.dump({"best_val_acc": best, "test_report": rep, "n_train": len(tr), "n_val": len(va),
               "n_test": len(te)}, open("reports/eye_cnn_metrics.json", "w"), indent=2)
    print("Saved: models/eye_cnn.pth and reports/eye_cnn_*")


if __name__ == "__main__":
    main()
